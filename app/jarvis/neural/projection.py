"""Read-only projections of the brain: Obsidian markdown snapshots (one-way; nothing in the vault executes).

Each export is generated from a journaled graph version. Notes carry a "generated, do not edit" banner; editing
them changes nothing in Jarvis. Wiki links are for browsing only. No payloads, secrets or request text are
written: only neuron contracts, synapses and aggregate verified statistics.
"""
from __future__ import annotations

from pathlib import Path
import re
from typing import Any, Dict, List, Optional

BANNER = ('> Generated by the Jarvis brain from journaled graph version {version}. Read-only projection: '
          'editing this note changes nothing.\n\n')


def _slug(node_id: str) -> str:
    return re.sub(r'[^A-Za-z0-9._-]+', '_', node_id.replace('@', '_'))


def _ports(rows: List[Dict[str, Any]]) -> str:
    return ', '.join(f'`{p["name"]}: {p["type"]}{"" if p.get("required", True) else "?"}`' for p in rows) or '(none)'


def _neuron_note(neuron: Dict[str, Any], out: List[Dict[str, Any]], inc: List[Dict[str, Any]], version: int,
                 stats: List[Dict[str, Any]]) -> str:

    lines = [BANNER.format(version=version), f'# {neuron["node_id"]}\n', f'{neuron.get("description", "")}\n',
             '| Field | Value |', '|---|---|']
    for key in ('kind', 'capability', 'provider', 'contract', 'side_effect_class', 'privilege', 'privacy', 'runtime',
                'status', 'tool'):
        lines.append(f'| {key} | {neuron.get(key)} |')
    lines.append(f'| inputs | {_ports(neuron.get("inputs", []))} |')
    lines.append(f'| outputs | {_ports(neuron.get("outputs", []))} |')
    if neuron.get('requirements'):
        lines.append(f'| requirements | {", ".join(neuron["requirements"])} |')
    if out:
        lines += ['', '## Sends to', ''] + [f'- [[{_slug(s["target"])}]] via `{s["data_type"]}` ({s["mode"]})'
                                             for s in out]
    if inc:
        lines += ['', '## Receives from', ''] + [f'- [[{_slug(s["source"])}]] via `{s["data_type"]}` ({s["mode"]})'
                                                  for s in inc]
    if stats:
        lines += ['', '## Verified outcomes', '', '| Context | Verified ok | Failed |', '|---|---|---|']
        lines += [f'| {r["context"]} | {r["successes"]} | {r["failures"]} |' for r in stats]
    return '\n'.join(lines) + '\n'


def export_obsidian(journal: Any, folder: Path, version: Optional[int] = None, wired_only: bool = True) -> Dict[str, Any]:
    """Write one note per (wired) neuron plus an index with a Mermaid map of the wired core. Returns counts."""
    snapshot = journal.graph(version)
    if snapshot is None:
        raise ValueError('no graph version is journaled yet')
    version = snapshot['version']
    folder = Path(folder)
    notes = folder / 'neurons'
    notes.mkdir(parents=True, exist_ok=True)
    synapses = snapshot['synapses']
    wired = {s['source'] for s in synapses} | {s['target'] for s in synapses}
    stats: Dict[str, List[Dict[str, Any]]] = {}
    for row in journal.stats():
        stats.setdefault(row['node_id'], []).append(row)
    written = 0
    for neuron in snapshot['neurons']:
        node_id = neuron['node_id']
        if wired_only and node_id not in wired:
            continue
        out = [s for s in synapses if s['source'] == node_id]
        inc = [s for s in synapses if s['target'] == node_id]
        (notes / f'{_slug(node_id)}.md').write_text(_neuron_note(neuron, out, inc, version, stats.get(node_id, [])),
                                                     encoding='utf-8')
        written += 1
    kinds: Dict[str, int] = {}
    for neuron in snapshot['neurons']:
        kinds[neuron['kind']] = kinds.get(neuron['kind'], 0) + 1
    mermaid = ['```mermaid', 'flowchart LR']
    ids = {node_id: f'n{i}' for i, node_id in enumerate(sorted(wired))}
    for s in synapses[:400]:
        arrow = '-.->' if s['mode'] == 'feedback' else '-->'
        mermaid.append(f'  {ids[s["source"]]}["{s["source"].split("@")[0]}"] {arrow}|{s["data_type"]}| '
                       f'{ids[s["target"]]}["{s["target"].split("@")[0]}"]')
    mermaid.append('```')
    index = [BANNER.format(version=version), '# Jarvis brain', '',
             f'{len(snapshot["neurons"])} neurons, {len(synapses)} synapses, {len(wired)} wired. Kinds: '
             + ', '.join(f'{k} {v}' for k, v in sorted(kinds.items())) + '.', '',
             '## Wired neurons', ''] + [f'- [[{_slug(n)}]]' for n in sorted(wired)] + ['', '## Map', ''] + mermaid
    (folder / 'Jarvis Brain.md').write_text('\n'.join(index) + '\n', encoding='utf-8')
    return {'version': version, 'notes': written, 'folder': str(folder)}
