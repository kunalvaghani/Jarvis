"""The live neuron registry: rebuilt from Jarvis's own code at every start, so the brain grows with Jarvis.

Sources (each read without starting anything): ToolRegistry SPECS, ``execution_strategy.METHODS``, MCP servers
(the allowlist in ``.jarvis/mcp.json``, plus live ``tools/list`` results when a connector reports them), the brain's
own core neurons and the sealed verifiers. A new tool, MCP tool or verifier added to Jarvis becomes a neuron the next
time the registry refreshes; nothing has to be regenerated by hand.

Growth: ``propose`` takes a neuron Jarvis (or a person) wants to add, for example a composite skill consolidated
from repeated verified routes (Phase 4). It must pass the same contract validation. A read-only neuron built only
from already active neurons is activated at once; anything that can change the world waits as ``proposed`` until
the user approves it (``approve``). Proposals are journaled, so they survive restarts and can be rolled back.
"""
from __future__ import annotations

import json
from pathlib import Path
import threading
from typing import Any, Callable, Dict, Iterable, List, Optional, Tuple

from pydantic import ValidationError

from . import catalog
from .contracts import Neuron, Port

APP = Path(__file__).resolve().parents[2]


def ports(specs: Iterable[str]) -> Tuple[Port, ...]:
    rows = []
    for spec in specs:
        name, kind = spec.split(':', 1)
        rows.append(Port(name=name, type=kind.rstrip('?'), required=not kind.endswith('?')))
    return tuple(rows)


def _privilege(effect: str, approval: str = 'none') -> str:
    if approval != 'none' or effect in ('destructive', 'external_write'):
        return 'approval_required'
    return 'read' if effect == 'read_only' else 'write'


def tool_neurons() -> List[Neuron]:
    from ..toolkits import TOOLS as KIT
    from ..tools import SPECS
    rows = []
    for spec in SPECS:
        contract = catalog.TOOLS.get(spec.name)
        effect = catalog.side_effect(spec.name, spec.approval)
        secrets = tuple(f'secret:{name}' for name in (KIT[spec.name][2] if spec.name in KIT else ()))
        if contract:
            inputs, outputs, _, runtime = contract
            explicit = 'explicit'
        else:
            network = spec.backend in ('toolkit', 'browser', 'realtime', 'firecrawl', 'github', 'email', 'dom',
                                        'duckduckgo', 'webscraper', 'mcp', 'cloud', 'deerflow')
            inputs, outputs, runtime, explicit = ('request:Text',), ('result:Text',), \
                ('local_or_network' if network else 'local'), 'derived'
        rows.append(Neuron.model_validate(dict(
            node_id=f'tool.{spec.name}@v1', kind='tool', capability=f'{spec.backend}.{spec.name}',
            provider=f'jarvis.tools.ToolRegistry ({spec.backend})', inputs=ports(inputs), outputs=ports(outputs),
            contract=explicit, runtime=runtime, privilege=_privilege(effect, spec.approval),
            privacy='public_data_only' if runtime == 'network' else 'local_private', side_effect_class=effect,
            requirements=secrets, tool=spec.name, description=spec.description[:600], source='jarvis/tools.py SPECS')))
    return rows


def method_neurons() -> List[Neuron]:
    from ..execution_strategy import METHODS
    rows = []
    for method in METHODS:
        writes = bool(set(method.operations) - {'read', 'inspect', 'text'})
        effect = 'local_write' if writes else 'read_only'
        rows.append(Neuron.model_validate(dict(
            node_id=f'method.{method.id.replace("-", "_").lower()}@v1', kind='tool',
            capability=f'{method.domain}.{"/".join(sorted(method.operations))}',
            provider=f'jarvis.execution_strategy ({method.tool})', inputs=ports(('request:Text',)),
            outputs=ports(('result:Text',)), privilege=_privilege(effect), side_effect_class=effect,
            requirements=tuple(method.requires), tool=method.tool, timeout_ms=None,
            resource_cost={'gpu_vram_mb': 0, 'expected_latency_ms': method.latency_ms, 'cost': method.cost},
            description=(method.note or f'{method.tier} {method.domain} method, verified by {method.verification}')[:600],
            source='jarvis/execution_strategy.py METHODS')))
    return rows


def mcp_config(base: Path = APP) -> Dict[str, Dict[str, Any]]:
    path = base / '.jarvis' / 'mcp.json'
    try:
        data = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return {}
    servers = data.get('servers') or data.get('mcpServers') or data
    return {name: spec for name, spec in servers.items() if isinstance(spec, dict)}


def mcp_neuron(server: str, tool: str, enabled: bool, description: str = '', schema: Optional[Dict[str, Any]] = None
               ) -> Neuron:
    effect = catalog.side_effect(tool)
    clean = tool.replace('-', '_').lower()
    return Neuron.model_validate(dict(
        node_id=f'mcp.{server.lower()}.{clean}@v1', kind='mcp', capability=f'{server}.{tool}',
        provider=f'jarvis.mcp_bridge ({server})', inputs=ports(('request:Text',)), outputs=ports(('result:Text',)),
        runtime='local_or_network', privilege='approval_required', side_effect_class=effect,
        requirements=(f'mcp_server:{server}',), healthcheck='mcp_status', tool='mcp_call',
        status='active' if enabled else 'disabled',
        description=(description or ('schema: ' + ','.join(sorted((schema or {}).get('properties', {})))
                                     if schema else 'allowlisted MCP tool'))[:600],
        source='.jarvis/mcp.json allow_tools' + (' + tools/list' if schema is not None else '')))


def mcp_neurons(base: Path = APP) -> List[Neuron]:
    rows = []
    for server, spec in sorted(mcp_config(base).items()):
        for tool in sorted(spec.get('allow_tools', [])):
            rows.append(mcp_neuron(server, tool, bool(spec.get('enabled'))))
    return rows


def core_neurons() -> List[Neuron]:
    rows = []
    for name, (kind, provider, inputs, outputs, effect, tool, text) in catalog.CORE.items():
        rows.append(Neuron.model_validate(dict(
            node_id=f'{name}@v1', kind=kind, capability=name, provider=provider, inputs=ports(inputs),
            outputs=ports(outputs), contract='explicit',
            privilege='approval_required' if name in catalog.APPROVAL_CORE or effect in ('destructive', 'external_write')
            else ('read' if effect == 'read_only' else 'write'),
            side_effect_class=effect, tool=tool or None, description=text, source='jarvis/neural/catalog.py CORE',
            requirements=('flag:control.api_routes',) if kind == 'route' else catalog.CORE_REQUIREMENTS.get(name, ()))))
    return rows


SOURCES: Dict[str, Callable[[], List[Neuron]]] = {
    'tools': tool_neurons, 'methods': method_neurons, 'mcp': mcp_neurons, 'core': core_neurons,
}


class RegistryError(ValueError):
    pass


class Registry:
    """All neurons Jarvis has right now. Thread-safe; ``refresh`` re-reads every source."""

    def __init__(self, journal: Any = None, sources: Optional[Dict[str, Callable[[], List[Neuron]]]] = None) -> None:
        self.journal, self.sources = journal, dict(SOURCES if sources is None else sources)
        self.nodes: Dict[str, Neuron] = {}
        self.errors: List[str] = []
        self._lock = threading.RLock()

    # Discovery ---------------------------------------------------------------------------------------------
    def refresh(self) -> 'Registry':
        nodes: Dict[str, Neuron] = {}
        errors: List[str] = []
        for name, source in self.sources.items():
            try:
                found = source()
            except (ImportError, ValidationError, OSError, ValueError) as error:
                errors.append(f'{name}: {type(error).__name__}: {error}'[:400])
                continue
            for neuron in found:
                if neuron.node_id in nodes:
                    errors.append(f'duplicate neuron {neuron.node_id} from {name}')
                    continue
                nodes[neuron.node_id] = neuron
        if self.journal is not None:
            for row in self.journal.proposals():  # Approved or pending growth survives restarts.
                try:
                    neuron = Neuron.model_validate(row)
                except ValidationError as error:
                    errors.append(f'journaled proposal invalid: {error}'[:400])
                    continue
                if neuron.status == 'disabled':
                    nodes[neuron.node_id] = neuron  # a retirement outlives the source that defines the neuron
                else:
                    nodes.setdefault(neuron.node_id, neuron)
        with self._lock:
            self.nodes, self.errors = nodes, errors
        return self

    def merge_mcp_tools(self, server: str, tools: Iterable[Dict[str, Any]], base: Path = APP) -> Dict[str, List[str]]:
        """Add a live ``tools/list`` result (all pages). Only allowlisted tools become neurons; the rest are refused."""
        spec = mcp_config(base).get(server)
        allowed = set((spec or {}).get('allow_tools', []))
        added, refused = [], []
        with self._lock:
            for tool in tools:
                name = str(tool.get('name', ''))
                if not spec or name not in allowed:
                    refused.append(name)
                    continue
                neuron = mcp_neuron(server, name, bool(spec.get('enabled')), str(tool.get('description', '')),
                                    tool.get('inputSchema') if isinstance(tool.get('inputSchema'), dict) else {})
                self.nodes[neuron.node_id] = neuron
                added.append(neuron.node_id)
        return {'added': added, 'refused': refused}

    # Growth -------------------------------------------------------------------------------------------------
    def propose(self, data: Dict[str, Any], built_from: Iterable[str] = (), proposer: str = 'jarvis') -> Neuron:
        """Validate a new neuron. Read-only composites of active neurons activate; everything else waits."""
        built = list(built_from)
        try:
            neuron = Neuron.model_validate({**data, 'status': 'proposed'})
        except ValidationError as error:
            raise RegistryError(f'invalid neuron: {error}') from None
        with self._lock:
            if neuron.node_id in self.nodes:
                raise RegistryError(f'{neuron.node_id} already exists; bump its version instead')
            missing = [n for n in built if self.nodes.get(n) is None or self.nodes[n].status != 'active']
            if missing:
                raise RegistryError(f'built from neurons that are not active: {missing}')
            parents_safe = all(self.nodes[n].side_effect_class == 'read_only' for n in built)
            if neuron.side_effect_class == 'read_only' and neuron.contract == 'explicit' and built and parents_safe:
                neuron = neuron.model_copy(update={'status': 'active'})
            self.nodes[neuron.node_id] = neuron
        if self.journal is not None:
            self.journal.save_proposal(neuron, built, proposer)
        return neuron

    def approve(self, node_id: str, approver: str = 'user') -> Neuron:
        with self._lock:
            neuron = self.nodes.get(node_id)
            if neuron is None or neuron.status != 'proposed':
                raise RegistryError(f'{node_id} is not a pending proposal')
            if neuron.side_effect_class == 'unknown':
                raise RegistryError(f'{node_id} needs a side-effect class before approval')
            neuron = neuron.model_copy(update={'status': 'active'})
            self.nodes[node_id] = neuron
        if self.journal is not None:
            self.journal.save_proposal(neuron, [], approver)
        return neuron

    def disable(self, node_id: str, reason: str, actor: str = 'user') -> Neuron:
        """Retire a neuron (status disabled, journalled with the reason; it stops being eligible). Automatic
        retirement (actor 'lifecycle') is limited to learned neurons; the user may retire any neuron."""
        with self._lock:
            neuron = self.nodes.get(node_id)
            if neuron is None or neuron.status != 'active':
                raise RegistryError(f'{node_id} is not an active neuron')
            if actor != 'user' and neuron.provider != 'jarvis.neural.learning':
                raise RegistryError(f'{node_id} is built in: only the user can retire it')
            neuron = neuron.model_copy(update={'status': 'disabled', 'description':
                                               (neuron.description + f' [retired by {actor}: {reason}]')[:500]})
            self.nodes[node_id] = neuron
        if self.journal is not None:
            self.journal.save_proposal(neuron, [], actor)
        return neuron

    def restore(self, node_id: str, actor: str = 'user') -> Neuron:
        """Bring a retired neuron back (the user's decision)."""
        with self._lock:
            neuron = self.nodes.get(node_id)
            if neuron is None or neuron.status != 'disabled':
                raise RegistryError(f'{node_id} is not a retired neuron')
            neuron = neuron.model_copy(update={'status': 'active'})
            self.nodes[node_id] = neuron
        if self.journal is not None:
            self.journal.save_proposal(neuron, [], actor)
        return neuron

    # Reads --------------------------------------------------------------------------------------------------
    def get(self, node_id: str) -> Optional[Neuron]:
        return self.nodes.get(node_id)

    def by_tool(self, tool: str) -> Optional[Neuron]:
        return self.nodes.get(f'tool.{tool}@v1')

    def active(self) -> List[Neuron]:
        return [n for n in self.nodes.values() if n.status == 'active']

    def summary(self) -> Dict[str, Any]:
        kinds: Dict[str, int] = {}
        effects: Dict[str, int] = {}
        for neuron in self.nodes.values():
            kinds[neuron.kind] = kinds.get(neuron.kind, 0) + 1
            effects[neuron.side_effect_class] = effects.get(neuron.side_effect_class, 0) + 1
        return {'neurons': len(self.nodes), 'active': len(self.active()), 'kinds': kinds, 'side_effects': effects,
                'explicit_contracts': sum(n.contract == 'explicit' for n in self.nodes.values()),
                'errors': list(self.errors)}
