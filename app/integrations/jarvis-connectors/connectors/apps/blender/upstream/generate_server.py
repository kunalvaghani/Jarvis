"""Developer utility: generate concrete annotated MCP tools from the canonical catalog.
Safe to rerun after catalog changes. Generated output contains no runtime exec/eval.
"""
from __future__ import annotations
from pathlib import Path
from blender_connector.catalog import ACTIONS, MISSING
import json

TYPES={'str':'str','int':'int','float':'float','bool':'bool','list':'list','dict':'dict','json':'Any'}
out=['''"""Autogenerated MCP adapter: every Blender action has its own named tool.
DO NOT modify manually; regenerate using python generate_server.py.
Stdout reserved for MCP JSON-RPC; bridge must already be running in Blender.
"""
from __future__ import annotations
from typing import Any
try:
    from mcp.server import MCPServer  # official MCP SDK v2
except ImportError:
    from mcp.server.fastmcp import FastMCP as MCPServer  # SDK v1 compatibility
from blender_connector.connector import BlenderConnector
from blender_connector.catalog import ACTIONS
from blender_connector.base import ConnectorError
from typing import Callable

mcp = MCPServer('jarvis-blender')

# Host-side approval must be supplied via Jarvis policy. By default the MCP
# standalone server denies destructive and filesystem actions. To enable them,
# inject a host approval_callback after explicit user confirmation.
connector = BlenderConnector()
''']
for name, action in ACTIONS.items():
    args=[]; param_keys=[]
    for key, field in action.fields.items():
        typ=TYPES[field.kind]
        nullable=field.default is None
        if field.default is MISSING:
            args.append(f'{key}: {typ}')
        elif nullable:
            args.append(f'{key}: {typ} | None = None')
        else:
            args.append(f'{key}: {typ} = {repr(field.default)}')
        param_keys.append(f'{key!r}: {key}')
    # required params must precede optional params for valid Python function signature
    req=[x for x in args if ' = ' not in x]
    opt=[x for x in args if ' = ' in x]
    signature=', '.join(req+opt)
    s=f'''\n@mcp.tool()\nasync def blender_{name}({signature}) -> dict:\n    """{action.description}. Risk classification: {action.risk}."""\n    return await connector.execute({name!r}, {{{', '.join(param_keys)}}}, wait={False if name in {'render_animation','render_still','render_preview'} else True})\n'''
    out.append(s)
out.append('''
@mcp.tool()
async def blender_bridge_health() -> dict:
    """Check Blender bridge connectivity without changing a project."""
    return await connector.health()

@mcp.tool()
async def blender_wait_job(job_id: str, timeout_seconds: float = 30.0) -> dict:
    """Wait for a Blender job, including long renders; timeout does not cancel work."""
    return await connector.wait_job(job_id,timeout=timeout_seconds)

@mcp.tool()
async def blender_job_status(job_id: str) -> dict:
    """Inspect an in-flight or completed Blender job without waiting."""
    return await connector.job_status(job_id)

if __name__ == '__main__':
    mcp.run()
''')
p=Path(__file__).parent/'server.py';p.write_text(''.join(out),encoding='utf-8')
print(f'Generated {len(ACTIONS)+3} named MCP tools into {p}')
